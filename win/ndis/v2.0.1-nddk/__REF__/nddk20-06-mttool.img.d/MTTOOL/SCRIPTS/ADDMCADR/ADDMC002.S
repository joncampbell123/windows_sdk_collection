;*****************************************************************************
;*
;*   File: ADDMC002.S - Script file to test the AddMulticastAddress primitive.
;*
;*   Description: Verify operation of AddMulticastAddress by adding many
;*                mutlicast addresses.
;*                Tests include:
;*                   Add addresses until an error is returned.
